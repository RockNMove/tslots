-- Модель: int_balance__agent_slot_item_daily_spine
-- Инвариант: is_used принимает только значения 1 или 2 (0 отфильтрован в модели).
-- Ответственность: полнота логики флага занятости ячейки.
--   Значение 1 — ячейка физически занята (close > 0 или однодневный реальный оборот).
--   Значение 2 — ошибка данных (отрицательный остаток), строка сохраняется для диагностики.
--   Значение 0 — ячейка пуста, отфильтровывается в WHERE модели.
--   Любое другое значение означает что CASE-логика не обработала какой-то сценарий.
-- При нарушении: появился новый граничный случай не предусмотренный CASE,
--   либо нарушена фильтрация WHERE b.is_used != 0 в финальном SELECT модели.
SELECT
    id
    , slot_id
    , agent_id
    , item_id
    , moment_day
    , is_used
    , close_slot_balance
    , open_slot_balance
    , real_in
    , real_out
FROM {{ ref('int_balance__agent_slot_item_daily_spine') }}
WHERE is_used NOT IN (1, 2)
